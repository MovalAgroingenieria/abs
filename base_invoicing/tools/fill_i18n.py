def po_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

def format_msgstr(trans, multiline=False):
    if not trans:
        return 'msgstr ""'
    if "\n" in trans or len(trans) > 76:
        lines = trans.replace("\\n", "\n").split("\n")
        out = 'msgstr ""\n'
        for line in lines:
            escaped = po_escape(line)
            out += f'"{escaped}\\n"\n'
        return out.rstrip("\\n\"\n") + '"\n' if out.endswith('\\n"\n') else out
    return f'msgstr "{po_escape(trans)}"'

def normalize_msgid(s):
    """Extract and normalize msgid value from block."""
    s = s.replace('\\n', '\n').replace('\\"', '"')
    return ' '.join(s.split())

